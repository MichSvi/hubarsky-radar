export const STRINGS: Record<Lang, Strings> = { sk, en };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('lang');
    if (saved === 'sk' || saved === 'en') return saved;
  } catch {}
  // Slovak is the default; English via the language switch or ?lang=en.
  if (new URLSearchParams(location.search).get('lang') === 'en') return 'en';
  return 'sk';
}
